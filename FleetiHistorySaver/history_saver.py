"""
FleetiHistorySaver - MongoDB-based conversation history management
Saves and loads conversation history from MongoDB collection FleetiMessages
"""

import os
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
from dotenv import load_dotenv
from pymongo import MongoClient
from bson import ObjectId

# Load environment variables
load_dotenv()


class FleetiHistorySaver:
    """
    Manages conversation history in MongoDB.
    One document per session, with messages array.
    """
    
    def __init__(
        self,
        session_id: str = "default_session",
        sub_tenant_id: str = "",
        mongo_db: Optional[str] = None,
    ):
        """
        Initialize the history saver.
        
        Args:
            session_id: Session ID (hardcoded for now, will be dynamic later)
            sub_tenant_id: Sub-tenant ID to associate with this session
        """
        mongo_uri = os.getenv("MONGO_URI")
        resolved_mongo_db = mongo_db or os.getenv("MONGO_DB")
        
        if not mongo_uri or not resolved_mongo_db:
            raise RuntimeError("MONGO_URI must be set and mongo_db must be provided (or MONGO_DB set in .env)")
        
        self.client = MongoClient(mongo_uri)
        self.db = self.client[resolved_mongo_db]
        self.db_name = resolved_mongo_db
        self.session_id = session_id
        self.sub_tenant_id = sub_tenant_id
        self.collection_name = "FleetiMessages"
        
        # Ensure collection exists
        self._ensure_collection_exists()
    
    def _ensure_collection_exists(self):
        """Create collection if it doesn't exist."""
        if self.collection_name not in self.db.list_collection_names():
            self.db.create_collection(self.collection_name)
            print(f"Created collection: {self.collection_name}")
    
    def load_session_history(self) -> List[Dict[str, str]]:
        """
        Load conversation history for the current session from MongoDB.
        Returns list of conversation entries in format: [{"user": "...", "assistant": "..."}, ...]
        
        Returns:
            List of conversation history entries
        """
        session_doc = self.db[self.collection_name].find_one({"sessionId": self.session_id})
        
        if not session_doc:
            return []
        
        # Convert MongoDB messages to ConversationClassifier format
        history = []
        messages = session_doc.get("messages", [])
        
        for msg in messages:
            if msg.get("type") == "general":
                history.append({
                    "user": msg.get("refined_message", msg.get("user_input", "")),
                    "assistant": msg.get("llm_response", "")
                })
            elif msg.get("type") == "fleet":
                history.append({
                    "user": msg.get("refined_message", msg.get("user_input", "")),
                    "assistant": msg.get("human_response", "LLM RESPONSE")
                })
        
        return history
    
    def save_general_message(
        self,
        user_input: str,
        refined_message: str,
        llm_response: str
    ):
        """
        Save a general conversation message to MongoDB.
        
        Args:
            user_input: Original user input
            refined_message: Refined user message
            llm_response: LLM response
        """
        message = {
            "type": "general",
            "user_input": user_input,
            "refined_message": refined_message,
            "llm_response": llm_response,
            "timestamp": datetime.now(timezone.utc)
        }
        
        self._append_message(message)
    
    def save_fleet_message(
        self,
        user_input: str,
        refined_message: str,
        selected_collections: List[str],
        query: str,
        query_response: List[Dict[str, Any]],
        human_response: str
    ):
        """
        Save a fleet-related question and response to MongoDB.
        
        Args:
            user_input: Original user input
            refined_message: Refined user message
            selected_collections: List of selected collections (e.g., ["asset_details_base", "AvlRecord_base"])
            query: MongoDB query generated by LLM
            query_response: Response from MongoDB query execution
            human_response: Human-readable response generated by LLM
        """
        message = {
            "type": "fleet",
            "user_input": user_input,
            "refined_message": refined_message,
            "selected_collections": selected_collections,
            "query": query,
            "query_response": query_response,
            "human_response": human_response,
            "timestamp": datetime.now(timezone.utc)
        }
        
        self._append_message(message)
    
    def _append_message(self, message: Dict[str, Any]):
        """
        Append a message to the session document in MongoDB.
        Creates document if it doesn't exist, appends to messages array if it does.
        Sets sub_tenant_id when creating a new session document.
        
        Args:
            message: Message dictionary to append
        """
        # Try to update existing document
        result = self.db[self.collection_name].update_one(
            {"sessionId": self.session_id},
            {
                "$push": {"messages": message},
                "$setOnInsert": {
                    "sessionId": self.session_id,
                    "sub_tenant_id": self.sub_tenant_id,
                    "created_at": datetime.now(timezone.utc)
                }
            },
            upsert=True
        )
        
        if result.upserted_id:
            print(f"Created new session document for sessionId: {self.session_id} with sub_tenant_id: {self.sub_tenant_id}")
        else:
            print(f"Appended message to existing session: {self.session_id}")
    
    def get_session_document(self) -> Optional[Dict[str, Any]]:
        """
        Get the full session document from MongoDB.
        
        Returns:
            Session document or None if not found
        """
        return self.db[self.collection_name].find_one({"sessionId": self.session_id})
    
    def clear_session(self):
        """Clear all messages for the current session."""
        self.db[self.collection_name].update_one(
            {"sessionId": self.session_id},
            {"$set": {"messages": []}}
        )
        print(f"Cleared messages for session: {self.session_id}")

